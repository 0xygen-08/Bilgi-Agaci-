def set_language(lang):
    global _current_lang
    if lang in TRANSLATIONS:
        _current_lang = lang

def t(key, **kwargs):
    text = TRANSLATIONS.get(_current_lang, TRANSLATIONS["tr"]).get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
